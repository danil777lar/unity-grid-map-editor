using System;
using System.Collections.Generic;
using System.IO;
using Larje.Core.Extensions;
using UnityEngine;

namespace Larje.MapEditor
{
    [Serializable]
    public abstract class MapLayer
    {
        private const string MESHES_FOLDER = "Assets/3D/Autogenerated/Meshes";

        [SerializeField] protected float _verticalOffset;
        [SerializeField] protected Vector2 _tileSize = Vector2.one;
        [SerializeField] protected Vector2 _tileOffset = Vector2.zero;
        [SerializeField] protected Transform _transform;

        [SerializeField] private string _name = "Layer";
        [SerializeField] private Color _color = Color.black;
        [SerializeField] private List<Tile> _filledTiles = new List<Tile>();

        [NonSerialized] private List<MapTool> _tools;

        public string Name
        {
            get => _name;
            set => _name = value;
        }

        public Color Color
        {
            get => _color;
            set => _color = value;
        }

        public Vector2 TileSize
        {
            get => _tileSize;
            set => _tileSize = new Vector2(Mathf.Max(0.1f, value.x), Mathf.Max(0.1f, value.y));
        }

        public Vector2 TileOffset
        {
            get => _tileOffset;
            set => _tileOffset = value;
        }

        public float VerticalOffset
        {
            get => _verticalOffset;
            set => _verticalOffset = value;
        }

        public MapTool CurrentTool { get; set; }
        public IReadOnlyList<Tile> FilledTiles => _filledTiles;
        public virtual float Height => 0f;

        public abstract void Build();

        public abstract Tile WorldPointToTile(Vector3 worldPoint);

        public abstract Tile WorldPointToTile(Vector3 worldPoint, Tile pointerDownTile);

        public abstract IReadOnlyCollection<Tile> GetTilesInRadius(Vector2 center, int radius);

        public abstract IReadOnlyCollection<Tile> GetTilesInRect(Vector2 from, Vector2 to, bool filled);

        public IReadOnlyCollection<MapTool> GetTools()
        {
            _tools ??= CreateTools();
            return _tools;
        }

        public bool ContainsTile(Tile tile)
        {
            return _filledTiles.Contains(tile) || _filledTiles.Contains(tile.Reversed());
        }

        public bool AddTile(Tile tile)
        {
            if (ContainsTile(tile))
            {
                return false;
            }

            _filledTiles.Add(tile);
            return true;
        }

        public bool RemoveTile(Tile tile)
        {
            return _filledTiles.Remove(tile) || _filledTiles.Remove(tile.Reversed());
        }

        public int AddTiles(IEnumerable<Tile> tiles)
        {
            int count = 0;
            foreach (Tile tile in tiles)
            {
                if (AddTile(tile))
                {
                    count++;
                }
            }

            return count;
        }

        public int RemoveTiles(IEnumerable<Tile> tiles)
        {
            int count = 0;
            foreach (Tile tile in tiles)
            {
                if (RemoveTile(tile))
                {
                    count++;
                }
            }

            return count;
        }

        public void ClearTiles()
        {
            _filledTiles.Clear();
        }

        public bool TryGetBounds(out Vector2Int min, out Vector2Int max)
        {
            min = Vector2Int.zero;
            max = Vector2Int.zero;
            if (_filledTiles.Count == 0)
            {
                return false;
            }

            min = Vector2Int.Min(_filledTiles[0].From, _filledTiles[0].To);
            max = Vector2Int.Max(_filledTiles[0].From, _filledTiles[0].To);
            foreach (Tile tile in _filledTiles)
            {
                min = Vector2Int.Min(min, Vector2Int.Min(tile.From, tile.To));
                max = Vector2Int.Max(max, Vector2Int.Max(tile.From, tile.To));
            }

            return true;
        }

        public void SetTransform(Transform target)
        {
            _transform = target;
        }

        public Vector3 TileToLocal(Vector2 tilePoint)
        {
            Vector3 result = new Vector3(tilePoint.x * _tileSize.x, _verticalOffset, tilePoint.y * _tileSize.y);
            result += new Vector3(_tileOffset.x, 0f, _tileOffset.y);
            return result;
        }

        public Vector2 LocalToTile(Vector3 localPoint)
        {
            Vector3 point = localPoint - new Vector3(_tileOffset.x, 0f, _tileOffset.y);
            return new Vector2(point.x / _tileSize.x, point.z / _tileSize.y);
        }

        public Vector3 TileToWorld(Vector2 tilePoint)
        {
            return _transform.TransformPoint(TileToLocal(tilePoint));
        }

        public Vector2 WorldToTile(Vector3 worldPoint)
        {
            return LocalToTile(_transform.InverseTransformPoint(worldPoint));
        }

        public bool TryRaycastMousePosition(out Vector3 position)
        {
#if UNITY_EDITOR
            Ray ray = UnityEditor.HandleUtility.GUIPointToWorldRay(Event.current.mousePosition);
            Plane plane = new Plane(_transform.up, _transform.position + _transform.up * _verticalOffset);
            if (plane.Raycast(ray, out float distance))
            {
                position = ray.GetPoint(distance);
                return true;
            }
#endif
            position = Vector3.zero;
            return false;
        }

        public void DrawGrid()
        {
#if UNITY_EDITOR
            GetGridCorners(out Vector2 min, out Vector2 max);
            UnityEditor.Handles.color = MapPalette.Grid;

            for (float x = min.x; x <= max.x; x++)
            {
                UnityEditor.Handles.DrawLine(TileToWorld(new Vector2(x, min.y)), TileToWorld(new Vector2(x, max.y)));
            }

            for (float y = min.y; y <= max.y; y++)
            {
                UnityEditor.Handles.DrawLine(TileToWorld(new Vector2(min.x, y)), TileToWorld(new Vector2(max.x, y)));
            }
#endif
        }

        public void DrawFilledTiles(bool selected)
        {
            Color color = _color.SetAlpha(selected ? _color.a : 0.2f);
            foreach (Tile tile in _filledTiles)
            {
                tile.Draw(color, Height, TileToWorld);
            }
        }

        public void DrawTile(Tile tile, Color color)
        {
            tile.Draw(color, Height, TileToWorld);
        }

        public virtual void DrawEditorGUI()
        {
#if UNITY_EDITOR
            DrawEditorGUIHeader("Base Settings");
            DrawEditorGUILine(() =>
                _tileOffset = UnityEditor.EditorGUILayout.Vector2Field("Tile Offset", _tileOffset));
            DrawEditorGUILine(() =>
                TileSize = UnityEditor.EditorGUILayout.Vector2Field("Tile Size", _tileSize));
            DrawEditorGUILine(() =>
                _verticalOffset = UnityEditor.EditorGUILayout.FloatField("Vertical Offset", _verticalOffset));

            UnityEditor.EditorGUILayout.Space(20f);
#endif
        }

        protected virtual List<MapTool> CreateTools()
        {
            return new List<MapTool>
            {
                new BrushTool(),
                new EraserTool(),
                new RectTool()
            };
        }

        protected GameObject CreateLayerObject()
        {
            GameObject layerObject = new GameObject(_name);
            layerObject.transform.SetParent(_transform);
            layerObject.transform.localPosition = Vector3.zero;
            layerObject.transform.localRotation = Quaternion.identity;
            layerObject.transform.localScale = Vector3.one;
            return layerObject;
        }

        protected void FinalizeMesh(Mesh mesh)
        {
            mesh.RecalculateNormals();
            mesh.RecalculateTangents();
            mesh.RecalculateBounds();
#if UNITY_EDITOR
            if (mesh.vertexCount > 0)
            {
                UnityEditor.Unwrapping.GenerateSecondaryUVSet(mesh);
            }
#endif
        }

        protected void DrawEditorGUIHeader(string header)
        {
#if UNITY_EDITOR
            UnityEditor.EditorGUILayout.LabelField(header, UnityEditor.EditorStyles.boldLabel);
            UnityEditor.EditorGUILayout.Space(5f);
#endif
        }

        protected void DrawEditorGUILine(Action drawCallback)
        {
#if UNITY_EDITOR
            UnityEditor.EditorGUILayout.BeginHorizontal();
            UnityEditor.EditorGUILayout.LabelField("|", GUILayout.Width(20f));
            drawCallback.Invoke();
            UnityEditor.EditorGUILayout.EndHorizontal();
#endif
        }

        protected void SaveMesh(Mesh mesh)
        {
#if UNITY_EDITOR
            mesh.name = _transform.GetPath().Replace("/", "_").Replace(" ", "") + "_" + _name;
            Directory.CreateDirectory(MESHES_FOLDER);

            string assetPath = $"{MESHES_FOLDER}/{mesh.name}.asset";
            if (UnityEditor.AssetDatabase.LoadAssetAtPath<Mesh>(assetPath) != null)
            {
                UnityEditor.AssetDatabase.DeleteAsset(assetPath);
            }

            UnityEditor.AssetDatabase.CreateAsset(mesh, assetPath);
            UnityEditor.AssetDatabase.SaveAssets();
#endif
        }

        private void GetGridCorners(out Vector2 min, out Vector2 max)
        {
            min = new Vector2(-5, -5);
            max = new Vector2(5, 5);

            foreach (Tile tile in _filledTiles)
            {
                min = Vector2.Min(min, Vector2Int.Min(tile.From, tile.To) - Vector2Int.one * 5);
                max = Vector2.Max(max, Vector2Int.Max(tile.From, tile.To) + Vector2Int.one * 5);
            }
        }
    }
}
